import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// A reviewable, complete text copy of the project sources. Generated assets,
// dependencies and screenshots are reproducible or binary, so are not inlined.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const destination = path.join(root, 'SOURCE-FILES.txt');
const excludedDirectories = new Set([
  'node_modules', 'dist', '.astro', '.git', '.wrangler', 'test-results',
  'playwright-report', 'screenshots', 'qa', '.qa', 'output', 'tmp', '.cache', '.npm-cache',
]);
const sourceExtensions = new Set([
  '.astro', '.ts', '.tsx', '.js', '.mjs', '.cjs', '.json', '.css',
  '.scss', '.md', '.txt', '.toml', '.yaml', '.yml', '.html', '.svg', '.xml',
  '.py', '.sh', '.ps1', '.d.ts',
]);
const sourceNames = new Set([
  '.gitignore', '.gitattributes', '.npmrc', '.nvmrc', '.node-version',
  '_headers', '_redirects', 'LICENSE', 'NOTICE',
]);
const sources = [];
const assets = new Map();

async function walk(directory) {
  const entries = (await readdir(directory, { withFileTypes: true }))
    .sort((left, right) => left.name.localeCompare(right.name, 'en'));
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    const relative = path.relative(root, absolute).split(path.sep).join('/');
    if (entry.isSymbolicLink()) continue;
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(entry.name)) await walk(absolute);
      continue;
    }
    if (!entry.isFile() || absolute === destination) continue;
    const extension = path.extname(entry.name).toLowerCase();
    if (sourceExtensions.has(extension) || sourceNames.has(entry.name)) {
      sources.push({ absolute, relative });
    } else {
      const folder = relative.startsWith('public/images/')
        ? relative.split('/').slice(0, 3).join('/')
        : path.posix.dirname(relative);
      const label = `${folder}/*${extension || ' (extensionless)'}`;
      const previous = assets.get(label) || { count: 0, bytes: 0 };
      const metadata = await stat(absolute);
      assets.set(label, { count: previous.count + 1, bytes: previous.bytes + metadata.size });
    }
  }
}

await walk(root);
sources.sort((left, right) => left.relative.localeCompare(right.relative, 'en'));
const chunks = [
  'ZOOMED ART — COMPLETE PROJECT SOURCE\n',
  'Generated by: node scripts/export-source.mjs\n',
  'Run from the site directory: npm install, then npm run dev.\n',
  'Production build: npm run build. Cloudflare Pages output directory: dist.\n\n',
  'This export contains every authored text source and configuration file in full,\n',
  'including the dependency lockfile. It excludes dependencies, build output,\n',
  'screenshots and binary media. Binary media are listed by directory below.\n',
  'The image preparation script and README describe how to reproduce assets.\n\n',
  'SOURCE FILE TREE\n',
  ...sources.map(({ relative }) => `  ${relative}\n`),
  '\nBINARY ASSET INVENTORY (not inlined)\n',
  ...[...assets].sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([label, { count, bytes }]) => `  ${label}: ${count} files, ${bytes.toLocaleString('en-US')} bytes\n`),
  '\n',
];

for (const { absolute, relative } of sources) {
  const contents = await readFile(absolute, 'utf8');
  chunks.push(`\n${'='.repeat(80)}\nFILE: ${relative}\n${'='.repeat(80)}\n\n`);
  chunks.push(contents);
  if (!contents.endsWith('\n')) chunks.push('\n');
}

await writeFile(destination, chunks.join(''), 'utf8');
console.log(`Exported ${sources.length} complete source files to ${destination}`);
